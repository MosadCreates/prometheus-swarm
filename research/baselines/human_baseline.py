"""Human-written baseline training script (Research Condition A).

This is NOT generated by Prometheus Swarm. It represents what an experienced
ML engineer would write by hand for a tabular task in ~30 minutes:

  - pandas read + basic cleaning (dropna on target, median/mode fill)
  - one-hot encode categoricals (pd.get_dummies)
  - LabelEncode the target
  - single stratified 80/20 split, fixed seed
  - LightGBM with sane defaults + one manual tuning pass (no Optuna)
  - save y_test.npy / y_pred.npy / y_prob.npy for the shared evaluator

Inputs come from environment variables (set by research/run_benchmark.py
Condition A runner):

  HUMAN_BASELINE_DATASET  - path to the CSV
  HUMAN_BASELINE_TARGET   - target column name
  HUMAN_BASELINE_TASK     - 'classification' | 'regression'
  HUMAN_BASELINE_OUT_DIR  - where to write the npy artifacts (checkpoints dir)
  JOB_ID                  - job identifier (for logging only)

The artifacts match the contract Forge's generated scripts use, so the SAME
run_arbiter_eval() computes metrics for conditions A, B and C — that
comparability is the point of a baseline. The DECISIONS here are human:
library choice, cleaning policy, split, and hyperparameters are hard-coded
judgment, not Scout reasoning or Optuna search.
"""

import os
import sys

import lightgbm as lgb
import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder

DATASET = os.environ["HUMAN_BASELINE_DATASET"]
TARGET = os.environ["HUMAN_BASELINE_TARGET"]
TASK = os.environ.get("HUMAN_BASELINE_TASK", "classification")
OUT_DIR = os.environ["HUMAN_BASELINE_OUT_DIR"]
SEED = 42


def main() -> int:
    print(f"[human-baseline] loading {DATASET} (target={TARGET}, task={TASK})")
    # A human tries the obvious delimiter first, then sniffs on failure.
    try:
        df = pd.read_csv(DATASET)
    except pd.errors.ParserError:
        df = pd.read_csv(DATASET, sep=None, engine="python")

    if TARGET not in df.columns:
        # Semicolon-delimited files read with the default engine land in one column
        df = pd.read_csv(DATASET, sep=";")
    if TARGET not in df.columns:
        df.columns = [c.strip().strip('"').split(";")[0] for c in df.columns]
    if TARGET not in df.columns:
        print(f"[human-baseline] target '{TARGET}' not found; columns: {list(df.columns)[:6]}")
        return 2

    df = df.dropna(subset=[TARGET])

    if TASK == "classification":
        y = LabelEncoder().fit_transform(df[TARGET].astype(str))
        X = df.drop(columns=[TARGET])
    else:
        y = pd.to_numeric(df[TARGET], errors="coerce").fillna(df[TARGET].median()).to_numpy()
        X = df.drop(columns=[TARGET])

    # Human cleaning policy: median-fill numerics, mode-fill rest, drop
    # everything with >50% missing, and drop ID/free-text columns by hand
    # (Ticket/Name would explode one-hot encoding and LightGBM rejects the
    # resulting feature names).
    num_cols = X.select_dtypes(include=np.number).columns
    other_cols = [c for c in X.columns if c not in num_cols]
    keep = [c for c in X.columns if X[c].isna().mean() <= 0.5]
    keep = [
        c
        for c in keep
        if not (c in other_cols and X[c].nunique(dropna=True) > max(50, int(0.05 * len(X))))
    ]
    num_cols = [c for c in keep if c in num_cols]
    other_cols = [c for c in keep if c in other_cols]
    X[num_cols] = X[num_cols].fillna(X[num_cols].median())
    for c in other_cols:
        mode = X[c].mode()
        X[c] = X[c].fillna(mode.iloc[0] if len(mode) else "missing")
    X = pd.get_dummies(X[keep], columns=other_cols, drop_first=True).astype(float)
    # LightGBM feature-name safety: plain identifiers only
    X.columns = [f"f{i}" for i in range(len(X.columns))]

    stratify = y if TASK == "classification" and np.bincount(y).min() > 1 else None
    X_tr, X_te, y_tr, y_te = train_test_split(
        X, y, test_size=0.2, random_state=SEED, stratify=stratify
    )

    if TASK == "classification":
        # Human's two-pass hyperparameter choice (defaults, then a modest tweak)
        params = dict(
            objective="binary",
            n_estimators=400,
            learning_rate=0.05,
            num_leaves=31,
            subsample=0.9,
            colsample_bytree=0.9,
            random_state=SEED,
            verbose=-1,
        )
        if len(np.unique(y)) > 2:
            params["objective"] = "multiclass"
            params["num_class"] = int(len(np.unique(y)))
        model = lgb.LGBMClassifier(**params)
        model.fit(X_tr, y_tr)
        y_pred = model.predict(X_te)
        try:
            y_prob = model.predict_proba(X_te)
        except Exception:
            y_prob = None
    else:
        params = dict(
            n_estimators=500,
            learning_rate=0.05,
            num_leaves=31,
            subsample=0.9,
            colsample_bytree=0.9,
            random_state=SEED,
            verbose=-1,
        )
        model = lgb.LGBMRegressor(**params)
        model.fit(X_tr, y_tr)
        y_pred = model.predict(X_te)
        y_prob = None

    os.makedirs(OUT_DIR, exist_ok=True)
    np.save(os.path.join(OUT_DIR, "y_test.npy"), y_te)
    np.save(os.path.join(OUT_DIR, "y_pred.npy"), y_pred)
    if y_prob is not None:
        np.save(os.path.join(OUT_DIR, "y_prob.npy"), y_prob)

    if TASK == "classification":
        try:
            auc = roc_auc_score(y_te, y_prob if y_prob is not None else y_pred, multi_class="ovr")
            print(f"[human-baseline] auc_roc={auc:.4f}")
        except Exception:
            pass

    print("[human-baseline] TRAINING_COMPLETE")
    return 0


if __name__ == "__main__":
    sys.exit(main())
