import os
import json
import pickle
import warnings
import numpy as np
import pandas as pd
import torch
from torch.utils.data import DataLoader, Dataset
from transformers import DistilBertTokenizer, DistilBertForSequenceClassification, AdamW
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score
from sklearn.preprocessing import LabelEncoder
warnings.filterwarnings("ignore")

import random
random.seed(42)
np.random.seed(42)
torch.manual_seed(42)

JOB_ID = "bench-tx04-48921c"
DATA_PATH = os.path.join(os.getenv("DATA_DIR", "./data"), "tx04_sms_spam.csv")
TARGET_COL = "label"
OUTPUT_DIR = os.path.join(os.getenv("OUTPUTS_DIR", "./outputs"), JOB_ID, "checkpoints")
os.makedirs(OUTPUT_DIR, exist_ok=True)

df = pd.read_csv(DATA_PATH, sep=",", encoding="utf-8")
text_col = [c for c in df.columns if c != TARGET_COL and df[c].dtype == "object"][0]
texts = df[text_col].astype(str).tolist()
labels = df[TARGET_COL].values

le = LabelEncoder()
labels = le.fit_transform(labels)
num_labels = len(le.classes_)

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
tokenizer = DistilBertTokenizer.from_pretrained("distilbert-base-uncased")
model = DistilBertForSequenceClassification.from_pretrained("distilbert-base-uncased", num_labels=num_labels)
model.to(device)


class TextDataset(Dataset):
    def __init__(self, texts, labels):
        self.encodings = tokenizer(texts, truncation=True, padding=True, max_length=128, return_tensors="pt")
        self.labels = torch.tensor(labels)
    def __len__(self): return len(self.labels)
    def __getitem__(self, idx):
        item = {k: v[idx] for k, v in self.encodings.items()}
        item["labels"] = self.labels[idx]
        return item


train_texts, val_texts, train_labels, val_labels = train_test_split(texts, labels, test_size=0.2, random_state=42)
train_dataset = TextDataset(train_texts, train_labels)
val_dataset = TextDataset(val_texts, val_labels)
train_loader = DataLoader(train_dataset, batch_size=16, shuffle=True)
val_loader = DataLoader(val_dataset, batch_size=16)

optimizer = AdamW(model.parameters(), lr=2e-5)

for epoch in range(3):
    model.train()
    total_loss = 0
    for batch in train_loader:
        batch = {k: v.to(device) for k, v in batch.items()}
        outputs = model(**batch)
        loss = outputs.loss
        loss.backward()
        optimizer.step()
        optimizer.zero_grad()
        total_loss += loss.item()
    avg_loss = total_loss / len(train_loader)
    print(f"Epoch {epoch+1}/3 | Train loss: {avg_loss:.4f}")

    model.eval()
    all_preds, all_labels = [], []
    with torch.no_grad():
        for batch in val_loader:
            batch = {k: v.to(device) for k, v in batch.items()}
            outputs = model(**batch)
            preds = torch.argmax(outputs.logits, dim=-1)
            all_preds.extend(preds.cpu().numpy())
            all_labels.extend(batch["labels"].cpu().numpy())
    val_acc = accuracy_score(all_labels, all_preds)
    print(f"Accuracy: {val_acc:.4f}")

checkpoint_path = os.path.join(OUTPUT_DIR, "best.ckpt")
with open(checkpoint_path, "wb") as f:
    pickle.dump({"model_state": model.state_dict(), "label_encoder": le}, f)
print(f"Model saved to {checkpoint_path}")
np.save(os.path.join(OUTPUT_DIR, "y_test.npy"), np.array(val_labels))
np.save(os.path.join(OUTPUT_DIR, "y_pred.npy"), np.array(all_preds))

result = {"checkpoint_path": checkpoint_path, "val_score": float(val_acc), "metric": "accuracy"}
_outputs_dir = os.getenv("OUTPUTS_DIR", "./outputs")
with open(os.path.join(_outputs_dir, JOB_ID, "result.json"), "w") as f:
    json.dump(result, f)
print("TRAINING_COMPLETE")